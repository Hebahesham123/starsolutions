import en from '@/data/site.json';
import ar from '@/data/site.ar.json';
import type { SiteContent } from './types';

export const LOCALES = ['en', 'ar'] as const;
export type Locale = (typeof LOCALES)[number];
export const DEFAULT_LOCALE: Locale = 'en';

export const LOCALE_META: Record<Locale, { label: string; dir: 'ltr' | 'rtl'; htmlLang: string; switchTo: string }> = {
  en: { label: 'English', dir: 'ltr', htmlLang: 'en', switchTo: 'عربي' },
  ar: { label: 'العربية', dir: 'rtl', htmlLang: 'ar', switchTo: 'English' },
};

export function isLocale(value: string): value is Locale {
  return (LOCALES as readonly string[]).includes(value);
}

/** Content for a locale. Arabic falls back to English for anything untranslated. */
export function getContent(locale: Locale): SiteContent {
  return (locale === 'ar' ? ar : en) as unknown as SiteContent;
}

/**
 * Build a href for a locale. English lives at the root (`/solutions`) so the
 * existing live URLs keep working; Arabic is prefixed (`/ar/solutions`).
 */
export function localeHref(locale: Locale, path: string): string {
  const clean = path === '/' ? '' : path.replace(/\/$/, '');
  return locale === DEFAULT_LOCALE ? clean || '/' : `/ar${clean}`;
}

/** Strip the locale prefix from a pathname, for the language switcher. */
export function stripLocale(pathname: string): string {
  if (pathname === '/ar') return '/';
  if (pathname.startsWith('/ar/')) return pathname.slice(3);
  return pathname;
}

