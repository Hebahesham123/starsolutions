/**
 * Writes supabase/migrations/0006_posts_seed.sql from the original posts
 * (src/data/posts.json + posts.ar.json), through src/lib/posts-legacy.ts —
 * the same conversion the site uses as its fallback, so the seeded rows and
 * the fallback can never disagree.
 *
 *   node scripts/generate-posts-seed.mjs
 *
 * Prints, per post and language, the word count and read time it will show.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const jiti = require('jiti')(fileURLToPath(import.meta.url), { interopDefault: true });
const { legacyRows } = jiti('../src/lib/posts-legacy.ts');
const { postWords, readingMinutes, readingLabel } = jiti('../src/lib/post-utils.ts');

const lit = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const json = (v) => {
  const text = JSON.stringify(v);
  if (text.includes('$post$')) throw new Error('content contains the $post$ delimiter');
  return `$post$${text}$post$::jsonb`;
};
const arr = (list) => (list.length ? `array[${list.map(lit).join(', ')}]::text[]` : "'{}'::text[]");

const rows = legacyRows();
const values = rows.map((r) => `(
  ${lit(r.slug)}, ${arr(r.previous_slugs)}, ${lit(r.status)}, ${lit(r.publish_at)}, ${lit(r.published_on)}, ${lit(r.content_updated_at)},
  ${arr(r.tags)}, ${lit(r.author_slug)}, ${json(r.related_services)}, ${r.cover ? json(r.cover) : 'null'}, ${r.show_toc},
  ${r.en_enabled}, ${r.ar_enabled},
  ${json(r.en)},
  ${json(r.ar)}
)`);

const sql = `-- 0006_posts_seed.sql — the ${rows.length} original posts, moved into public.posts.
--
-- Generated by scripts/generate-posts-seed.mjs from src/data/posts.json and
-- posts.ar.json. Run AFTER 0005_posts.sql. Safe to run more than once: a slug
-- that already exists is left alone (so it never overwrites edits made in /admin).
--
-- Same slugs (same URLs), authors, published dates and updated dates
-- (content_updated_at = 09:00 Cairo on the old "updated" day, exactly the
-- dateModified the pages had). Each body is unchanged up to its FAQ; the FAQ
-- is now question/answer pairs; a section after the FAQ became the CTA block.
-- Meta titles and descriptions come from what src/data/seo.json had.

insert into public.posts (
  slug, previous_slugs, status, publish_at, published_on, content_updated_at,
  tags, author_slug, related_services, cover, show_toc,
  en_enabled, ar_enabled, en, ar
) values
${values.join(',\n')}
on conflict (slug) do nothing;
`;

const out = fileURLToPath(new URL('../supabase/migrations/0006_posts_seed.sql', import.meta.url));
writeFileSync(out, sql.replace(/\n/g, '\r\n'));
console.log(`wrote ${out}`);
for (const r of rows) {
  for (const l of ['en', 'ar']) {
    if (!r[`${l}_enabled`]) continue;
    const w = postWords(r[l]);
    console.log(`${r.slug} [${l}] ${w} words → ${readingLabel(readingMinutes(w), l)} | faq ${r[l].faq.length} "${r[l].faq_title}" | cta ${r[l].cta.heading ? JSON.stringify(r[l].cta.heading) : '-'}`);
  }
}
